"""Shared geometry for CAD and acoustic simulation; coordinates in SI units."""

import csv
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def load_design() -> dict:
    return json.loads((ROOT / "mechanical/design.json").read_text())


def hex_sites(rings: int, pitch: float) -> np.ndarray:
    sites = []
    for q in range(-rings, rings + 1):
        for r in range(-rings, rings + 1):
            if 0 < max(abs(q), abs(r), abs(q + r)) <= rings:
                sites.append((pitch * (q + r / 2), pitch * np.sqrt(3) * r / 2))
    return np.asarray(sites, dtype=float)


def curved_array(design: dict | None = None) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Face centres, inward unit normals and upper/lower bank IDs."""
    d = load_design() if design is None else design
    radius = d["curvature_radius_mm"] * 1e-3
    xy = hex_sites(d["hex_rings"], d["hex_pitch_mm"] * 1e-3)
    squared = np.sum(xy**2, axis=1)
    if np.any(squared >= radius**2):
        raise ValueError("Array aperture must fit inside the curvature sphere")
    height = np.sqrt(radius**2 - squared)
    centres = np.vstack((np.column_stack((xy, height)), np.column_stack((xy, -height))))
    return centres, -centres / radius, np.repeat([0, 1], len(xy))


def mechanical_dimensions(design: dict | None = None) -> dict:
    d = load_design() if design is None else design
    radius = d["curvature_radius_mm"]
    rim_z = float(np.sqrt(radius**2 - d["cap_inner_aperture_radius_mm"]**2))
    base_top = -(radius + d["shell_thickness_mm"] + d["base_clearance_mm"])
    return {"rim_z_mm": rim_z, "base_top_mm": base_top,
            "base_bottom_mm": base_top - d["base_thickness_mm"],
            "lower_seat_z_mm": -rim_z - d["ear_thickness_mm"],
            "upper_seat_z_mm": rim_z}


def export_geometry() -> None:
    d = load_design()
    centres, normals, banks = curved_array(d)
    lines = ["// Generated by simulation/array_geometry.py; edit design.json instead."]
    for key, value in {**d, **mechanical_dimensions(d)}.items():
        if isinstance(value, (int, float)):
            lines.append(f"{key} = {value:.12g};")
    lines.append("upper_face_centres_mm = [")
    for p in centres[banks == 0] * 1e3:
        lines.append("  [" + ", ".join(f"{v:.12g}" for v in p) + "],")
    lines.append("];\n")
    (ROOT / "mechanical/generated_geometry.scad").write_text("\n".join(lines))
    count = len(centres) // 2
    capacitance = count * d["emitter_capacitance_pf"] * 1e-12
    (ROOT / "hardware/generated_driver_params.inc").write_text(
        "* Generated from mechanical/design.json by array_geometry.py\n"
        f"* {count} parallel emitters per bank; nominal capacitance only\n"
        f".param VM={d['bridge_supply_v']} FREQ={d['frequency_hz']}\n"
        f".param CBANK={capacitance:.12g} RDAMP={d['series_resistance_ohm']}\n"
        ".param LOAD_SCALE=1 RBRIDGE=0.5\n")
    (ROOT / "results").mkdir(exist_ok=True)
    with (ROOT / "results/array_geometry.csv").open("w", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(["bank", "element", "x_mm", "y_mm", "z_mm", "nx", "ny", "nz"])
        for bank in (0, 1):
            for index, (p, n) in enumerate(zip(centres[banks == bank], normals[banks == bank]), 1):
                writer.writerow(["upper" if bank == 0 else "lower", index, *(p * 1e3), *n])


if __name__ == "__main__":
    export_geometry()
